//! `deskpet new`: turn a glTF file into a pet package with a manifest whose
//! guesses (clips, head, blink) the agent then confirms on a contact sheet.

use std::path::Path;

use crate::model::{self, Model};

/// First clip whose lowercase name contains any of `words`.
fn find_clip<'a>(model: &'a Model, words: &[&str], skip: &[&str]) -> Option<&'a str> {
    model
        .clips
        .iter()
        .map(|c| c.name.as_str())
        .filter(|n| !skip.contains(n))
        .find(|n| words.iter().any(|w| n.to_lowercase().contains(w)))
}

fn quote(s: &str) -> String {
    format!("\"{}\"", s.replace('\\', "\\\\").replace('"', "\\\""))
}

/// The manifest text for `model`, with every guess marked as one.
pub fn manifest(name: &str, model_file: &str, model: &Model) -> String {
    let clips: Vec<&str> = model.clips.iter().map(|c| c.name.as_str()).collect();
    let idle = find_clip(
        model,
        &["idle", "breath", "stand", "survey", "wait", "rest"],
        &[],
    )
    .or(clips.first().copied());
    let skip: Vec<&str> = idle.into_iter().collect();
    let react = find_clip(
        model,
        &["jump", "happy", "react", "hit", "wave", "run"],
        &skip,
    );
    let mut used = skip.clone();
    used.extend(react);
    let fidget: Vec<&str> = clips
        .iter()
        .copied()
        .filter(|c| !used.contains(c))
        .collect();
    let head = model
        .nodes
        .iter()
        .map(|n| n.name.as_str())
        .find(|n| n.to_lowercase().contains("head"));
    let blink = model.morph_names.iter().find(|n| {
        let n = n.to_lowercase();
        n.contains("blink") || (n.contains("eye") && n.contains("clos"))
    });

    let mut s = String::new();
    s += &format!(
        "# Generated by `deskpet new`. Lines marked GUESS need a look on the contact sheet:\n#   deskpet render {name}\n"
    );
    s += &format!("name = {}\nmodel = {}\n", quote(name), quote(model_file));
    s += "# Degrees about Y that turn the model to face the camera. GUESS: check the turntable row.\n";
    s += "facing = 0\nheight = 260\nstyle = \"real\"\n\n[animations]\n";
    s += &format!(
        "# Clips in the model: {}\n",
        if clips.is_empty() {
            "none".into()
        } else {
            clips.join(", ")
        }
    );
    match idle {
        Some(c) => s += &format!("idle = {}  # GUESS\n", quote(c)),
        None => s += "# idle = \"...\"  # the model has no clips: the pet will only breathe\n",
    }
    s += &format!(
        "fidget = [{}]  # GUESS\n",
        fidget
            .iter()
            .map(|c| quote(c))
            .collect::<Vec<_>>()
            .join(", ")
    );
    match react {
        Some(c) => s += &format!("react = {}  # GUESS\n", quote(c)),
        None => s += "# react = \"...\"\n",
    }
    s += "\n[rig]\n";
    match head {
        Some(h) => s += &format!("head = {}  # GUESS\n", quote(h)),
        None => s += "# head = \"...\"  # no node named like a head; pick the neck or head joint\n",
    }
    s += "look_limit = 30\n";
    match blink {
        Some(b) => s += &format!("blink = {}  # GUESS\n", quote(b)),
        None => s += "# blink = \"...\"  # needs an eyes-closed morph target\n",
    }
    s += "\n[styles.real]\nkind = \"real\"\nfur = 0.012\nglow = [1.0, 0.9, 0.8]\n";
    s += "\n[styles.anime]\nkind = \"anime\"\noutline = 0.006\nbands = 2\nglow = [1.0, 0.9, 0.8]\n";
    s
}

/// Creates `dir` with the model copied in, a manifest and a license stub.
pub fn create(dir: &Path, source: &Path, name: Option<&str>) -> Result<(), String> {
    if dir.join("pet.toml").exists() {
        return Err(format!("{} already has a pet.toml", dir.display()));
    }
    let model = model::load(source)?;
    let ext = source.extension().and_then(|e| e.to_str()).unwrap_or("glb");
    if ext != "glb" {
        return Err(
            "only .glb is supported by `new`; a .gltf with side files must be copied by hand"
                .into(),
        );
    }
    std::fs::create_dir_all(dir).map_err(|e| format!("{}: {e}", dir.display()))?;
    let file = "model.glb";
    std::fs::copy(source, dir.join(file)).map_err(|e| format!("copy model: {e}"))?;
    let name = name
        .map(str::to_string)
        .or_else(|| dir.file_name().map(|n| n.to_string_lossy().into_owned()))
        .unwrap_or_else(|| "pet".into());
    std::fs::write(dir.join("pet.toml"), manifest(&name, file, &model))
        .map_err(|e| format!("write pet.toml: {e}"))?;
    let license = dir.join("LICENSE.md");
    if !license.exists() {
        std::fs::write(
            &license,
            format!("# {name}\n\nSource: TODO (where the model came from)\nLicense: TODO\n"),
        )
        .map_err(|e| format!("write LICENSE.md: {e}"))?;
    }
    Ok(())
}
